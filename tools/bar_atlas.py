"""Pack the bar's static textures (assets/tex/*.png) into one atlas, so the whole room is one draw call.
Run from the repo root after changing any of them:  python3 tools/bar_atlas.py
Writes assets/tex/bar_atlas.png and src/bar_atlas.js (where each texture sits in the atlas)."""
import json
from PIL import Image
KEYS = ['banner', 'barfront', 'black', 'bottles', 'brass', 'brick', 'ceiling', 'chrome', 'cola', 'concrete', 'counter', 'darkwood', 'felt',
        'jukebox', 'lantern', 'menuboard', 'neon_hino', 'neon_open', 'sodium', 'teal', 'tile', 'window', 'wood_floor', 'wood_panel', 'zep_strip']
imgs = {k: Image.open(f'assets/tex/{k}.png').convert('RGBA') for k in KEYS}
W = 256; x = y = rowh = 0; at = {}
for k in sorted(KEYS, key=lambda k: (-imgs[k].height, -imgs[k].width)):
    im = imgs[k]
    if x + im.width > W: x = 0; y += rowh; rowh = 0
    at[k] = (x, y); x += im.width; rowh = max(rowh, im.height)
H = 1
while H < y + rowh: H *= 2
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
rects = {}
for k in KEYS:
    atlas.paste(imgs[k], at[k])
    ax, ay = at[k]; w, h = imgs[k].size
    rects[k] = [round(ax / W, 6), round(ay / H, 6), round(w / W, 6), round(h / H, 6)]
atlas.save('assets/tex/bar_atlas.png', optimize=True)
open('src/bar_atlas.js', 'w').write("'use strict';\n// Generated by tools/bar_atlas.py: where each of the bar's static textures sits in TEX.bar_atlas.\n"
    "const BAR_ATLAS = " + json.dumps(rects, separators=(',', ':')) + ";   // [u0, v0, du, dv] per texture in TEX.bar_atlas\n")
print('atlas', W, 'x', H)
