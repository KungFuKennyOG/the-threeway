SKIN_AT = {'volkov': (34, 50)}   # colours sampled from the sheet itself

def hexrgb(h): return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255)

for name, (pal, back, side) in G.items():
    path = f'assets/tex/sheet_{name}.png'
    src = Image.open(path).convert('RGBA')
    top = src.crop((0, 0, 64, 64))
    out = Image.new('RGBA', (64, 128), (0, 0, 0, 0))   # power of two; rows 80-127 free for later panels
    out.paste(top, (0, 0))
    P = {k: (hexrgb(v) if v else top.getpixel(SKIN_AT[name])) for k, v in pal.items()}
    for ox, rows in ((0, back), (16, side)):
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), (name, ox)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row): out.putpixel((ox + x, 64 + y), P[ch])
    out.save(path)
    print(name, out.size)
